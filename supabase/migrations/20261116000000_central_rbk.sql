begin;

create table if not exists public."RBK DADOS" (
  row_id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  colecao text not null check (colecao in ('clients', 'itens', 'pagamentos', 'agenda')),
  id text not null,
  dados jsonb not null check (jsonb_typeof(dados) = 'object'),
  atualizado timestamptz not null default now(),
  constraint central_rbk_colecao_id unique (colecao, id)
);

alter table public."RBK DADOS" enable row level security;
revoke all on public."RBK DADOS" from public, anon, authenticated;
grant select, insert, update, delete on public."RBK DADOS" to authenticated;

drop policy if exists central_rbk_registros on public."RBK DADOS";
create policy central_rbk_registros on public."RBK DADOS" for all to authenticated
  using ((select auth.jwt()) -> 'app_metadata' ->> 'central_rbk' = 'true')
  with check ((select auth.jwt()) -> 'app_metadata' ->> 'central_rbk' = 'true');

insert into storage.buckets (id, name, public, file_size_limit)
values ('anexos', 'anexos', false, 52428800)
on conflict (id) do update set public = false;

drop policy if exists central_rbk_anexos_leitura on storage.objects;
create policy central_rbk_anexos_leitura on storage.objects for select to authenticated
  using (bucket_id = 'anexos' and (select auth.jwt()) -> 'app_metadata' ->> 'central_rbk' = 'true');

drop policy if exists central_rbk_anexos_envio on storage.objects;
create policy central_rbk_anexos_envio on storage.objects for insert to authenticated
  with check (bucket_id = 'anexos' and (select auth.jwt()) -> 'app_metadata' ->> 'central_rbk' = 'true');

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'RBK DADOS'
  ) then
    alter publication supabase_realtime add table public."RBK DADOS";
  end if;
end;
$$;

commit;

